//Sum and average of three numbers

import java.util.*;

public class Average {

  public static void main(int a, int b, int c) {
    int sum = 0;
    double avg = 0.0;
    sum = (a + b + c);
    avg = sum / 3.0;
    System.out.println("The sum=" + sum);
    System.out.println("The average=" + avg);
  }
}
