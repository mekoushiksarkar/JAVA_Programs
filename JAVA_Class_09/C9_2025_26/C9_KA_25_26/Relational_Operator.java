/* A program to demonstrate the use of Relational Operators*/

public class Relational_Operator {

  public static void main(String args[]) {
    int a = 25, b = 45;
    System.out.println("a > b is " + (a > b));
    System.out.println("a < b is " + (a < b));
    System.out.println("a == b is " + (a == b));
    System.out.println("a <= b is " + (a <= b));
    System.out.println("a >= b is " + (a >= b));
    System.out.println("a != b is " + (a != b));
  }
}
