/* ArrayLength.java */

public class ArrayLength
{
    public static void main(String args[]) {
        char chars[] = {'C','O','M','P','U','T','E','R'};
        System.out.println("Array length is: " + chars.length);
        for (int i = 0; i < chars.length; i++)
            System.out.println(chars[i]);
    }
}