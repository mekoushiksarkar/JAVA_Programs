/* StringArray.java */

public class StringArray
{
    public static void main(String args[])
    {
        String colours[] = {"RED", "BLUE", "GREEN"};
        System.out.println("colours[0]: " + colours[0]);
        System.out.println("colours[1]: " + colours[1]);
        System.out.println("colours[2]: " + colours[2]);
        System.out.println("colours[0].charAt(1): " + colours[0].charAt(1));
        System.out.println("colours[1].charAt(2): " + colours[1].charAt(2));
        System.out.println("colours[2].charAt(4): " + colours[2].charAt(4));
    }
}
