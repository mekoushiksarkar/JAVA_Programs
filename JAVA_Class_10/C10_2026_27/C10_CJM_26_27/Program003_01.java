class Main
{
    public static void main(String[] args)
    {
        int i,p,sum;sum=0;
        int m[]={12,13,14,15,16};
        p=m.length;
        for(i=0;i<p;i++)
            sum=sum+m[i];
        System.out.println("The sum of array elements:"+sum);
    }
}

