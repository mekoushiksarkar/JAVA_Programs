/* A program to demonstrate the use of the subtraction operator */

public class Subtraction_Operator
{
    public static void main (String args[])
    {
        int p=10, q=13, r=18;
        
        System.out.println("20-10 equals to " + (20-10));
        System.out.println("q-p equals to " + (q-p));
        System.out.println("r-p equals to " + (r-p));
    }
}
